export function resolveStep(step) {
  if (step.patternId) {
    const p = PATTERNS.find((x) => x.id === step.patternId);
    if (!p) throw new Error(`unknown pattern ${step.patternId}`);
    return {
      ...p,
      priorCoding: step.priorCoding === true || p.expect?.priorCoding === true,
      text: step.text || p.text,
    };
  }
  return {
    id: step.id || 'inline',
    family: step.family || 'inline',
    text: step.text,
    plane: step.plane,
    mode: step.mode ?? null,
    expect: step.expect || {},
    priorCoding: step.priorCoding === true,
  };
}
