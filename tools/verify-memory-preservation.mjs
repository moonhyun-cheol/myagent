import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { createServer } from 'node:http';
import os from 'node:os';
import path from 'node:path';
import { UserMemoryStore, getUserMemoryStore } from '../core/dist/memory/user-memory-store.js';
import { ProjectStore } from '../core/dist/projects/project-store.js';
import { SessionStore } from '../core/dist/sessions/session-store.js';
import { dispatchApiRequest } from '../core/dist/routes/dispatch.js';

const dir = mkdtempSync(path.join(os.tmpdir(), 'memory-preservation-'));
let server;
try {
  const store = new UserMemoryStore(path.join(dir, 'unit'));
  const active = store.add({ scope: 'project', project_id: 'old', text: 'private active knowledge' });
  const disabled = store.add({ scope: 'project', project_id: 'old', text: 'disabled knowledge' });
  store.update(disabled.id, { enabled: false });
  const pending = store.propose({ scope: 'project', project_id: 'old', text: 'unapproved knowledge', source_session_id: 'chat' });
  const rejected = store.propose({ scope: 'project', project_id: 'old', text: 'rejected knowledge' });
  store.reject(rejected.id);
  assert.equal(store.archiveProjects([{ id: 'old', title: 'Original project' }]), 4);
  assert.equal(store.archiveProjects([{ id: 'old', title: 'Changed title' }]), 0);
  assert.equal(store.list('old').project.length, 0);
  assert.equal(store.list().archived.length, 4);
  assert.equal(store.get(active.id).origin_project_title, 'Original project');
  assert.equal(store.get(active.id).created_at, active.created_at);
  assert.equal(store.get(active.id).enabled, true);
  assert.equal(store.get(pending.id).status, 'pending');
  assert.equal(store.get(rejected.id).status, 'rejected');
  assert.equal(store.formatForPrompt('old', 'chat'), '');
  assert.equal(store.formatForPrompt('new', 'unrelated'), '');
  assert.equal(store.approve(pending.id), null);
  assert.throws(() => store.update(active.id, { enabled: true }), (e) => e.code === 'ARCHIVED_LOCKED');
  assert.throws(() => store.batch({ ids: [active.id], project_id: 'old', action: 'move', target_scope: 'global' }), (e) => e.code === 'ARCHIVED_LOCKED');
  assert.equal(store.removeByProject(['old']), 0, 'archived knowledge survives later project cleanup');
  assert.throws(() => store.restore(active.id, { scope: 'global', id: 'x' }), (e) => e.code === 'INVALID_TARGET');
  store.restore(active.id, { scope: 'session', id: 'chat' });
  assert.equal(store.get(active.id).origin_project_title, 'Original project');
  assert.match(store.formatForPrompt(null, 'chat'), /private active knowledge/);
  assert.equal(store.formatForPrompt(null, 'other'), '');
  store.restore(disabled.id, { scope: 'project', id: 'new' });
  assert.equal(store.get(disabled.id).enabled, false);
  store.restore(pending.id, { scope: 'project', id: 'new' });
  assert.equal(store.formatForPrompt('new'), '');
  store.approve(pending.id);
  assert.match(store.formatForPrompt('new'), /unapproved knowledge/);
  store.restore(rejected.id, { scope: 'project', id: 'new' });
  assert.equal(store.get(rejected.id).status, 'rejected');
  assert.doesNotMatch(store.formatForPrompt('new'), /rejected knowledge/);
  const clash = store.add({ scope: 'project', project_id: 'dup', text: active.text });
  store.archiveProjects([{ id: 'dup', title: 'Duplicate' }]);
  const snapshot = () => readFileSync(path.join(dir, 'unit/user-memory.json'), 'utf8');
  const before = snapshot();
  assert.throws(() => store.restore(clash.id, { scope: 'session', id: 'chat' }), (e) => e.code === 'DUPLICATE_TEXT');
  assert.equal(snapshot(), before);
  for (let i = 0; i < 100; i++) store.add({ scope: 'project', project_id: 'full', text: `full ${i}` });
  assert.throws(() => store.restore(clash.id, { scope: 'project', id: 'full' }), (e) => e.code === 'SCOPE_FULL');
  assert.equal(new UserMemoryStore(path.join(dir, 'unit')).list().archived.length, 1);
  assert.equal(store.remove(clash.id), true);
  // Undo is scoped to the stamp of one archive call.
  const stamp = '2026-01-01T00:00:00.000Z';
  const undo = store.add({ scope: 'project', project_id: 'undo', text: 'undo me' });
  assert.equal(store.archiveProjects([{ id: 'undo' }], stamp), 1);
  assert.equal(store.unarchiveProjects(['undo'], 'other-stamp'), 0);
  assert.equal(store.formatForPrompt('undo'), '');
  assert.equal(store.unarchiveProjects(['undo'], stamp), 1);
  assert.equal(store.get(undo.id).archived_at, null);
  assert.match(store.formatForPrompt('undo'), /undo me/);
  writeFileSync(path.join(dir, 'unit/user-memory.json'), '{broken');
  assert.throws(() => store.archiveProjects([{ id: 'old' }]), (e) => e.code === 'MEMORY_READ_FAILED');
  assert.equal(readFileSync(path.join(dir, 'unit/user-memory.json'), 'utf8'), '{broken');

  // Exercise the actual HTTP dispatcher with isolated stores, never user data.
  const dataDir = path.join(dir, 'api');
  for (const name of ['config', 'projects', 'sessions']) mkdirSync(path.join(dataDir, name), { recursive: true });
  const projectStore = new ProjectStore(path.join(dataDir, 'projects'), dir);
  const sessionStore = new SessionStore(path.join(dataDir, 'sessions'), dir);
  const memory = getUserMemoryStore(dataDir);
  let readOnly = false;
  const ctx = { cqrRoot: dir, userConfigPath: path.join(dataDir, 'config/user.json'), projectStore, sessionStore,
    license: { assertFeature() {}, assertWritable() { if (readOnly) throw new Error('read only'); } } };
  server = createServer((req, res) => {
    dispatchApiRequest(ctx, req, res, new URL(req.url, 'http://127.0.0.1'), req.method).catch((e) => { res.statusCode = 500; res.end(JSON.stringify({ error: e.message })); });
  });
  await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
  const base = `http://127.0.0.1:${server.address().port}`;
  const call = async (url, method = 'GET', body) => {
    const res = await fetch(base + url, { method, headers: { 'Content-Type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) });
    return { status: res.status, data: await res.json() };
  };
  const p = projectStore.create({ title: 'Deleted root', kind: 'project' });
  sessionStore.ensure('moving-chat', { project_id: p.id });
  const note = memory.add({ scope: 'project', project_id: p.id, text: 'retained API knowledge' });
  assert.equal((await call(`/projects/${p.id}`, 'DELETE')).status, 200);
  assert.equal(sessionStore.load('moving-chat').project_id, null);
  assert.equal(memory.get(note.id).origin_project_title, 'Deleted root');
  assert.equal(memory.formatForPrompt(p.id, 'moving-chat'), '');
  assert.equal((await call('/memory')).data.archived.length, 1);
  assert.equal((await call(`/memory/${note.id}/restore`, 'POST', { scope: 'session', id: 'missing' })).status, 400);
  assert.equal((await call(`/memory/${note.id}/restore`, 'POST', { scope: 'global', id: 'all' })).status, 400);
  readOnly = true;
  assert.notEqual((await call(`/memory/${note.id}/restore`, 'POST', { scope: 'session', id: 'moving-chat' })).status, 200);
  assert.ok(memory.get(note.id).archived_at);
  readOnly = false;
  assert.equal((await call(`/memory/${note.id}/restore`, 'POST', { scope: 'session', id: 'moving-chat' })).status, 200);
  assert.match(memory.formatForPrompt(null, 'moving-chat'), /retained API knowledge/);
  const parentPath = path.join(dataDir, 'workspace');
  mkdirSync(parentPath);
  const parent = projectStore.upsertWorkspaceRoot(parentPath);
  const child = projectStore.create({ title: 'Child', kind: 'folder', parent_id: parent.id });
  const childNote = memory.add({ scope: 'project', project_id: child.id, text: 'child only' });
  assert.equal((await call(`/projects/${child.id}`, 'DELETE')).status, 200);
  assert.ok(memory.get(childNote.id).archived_at);
  assert.equal(memory.formatForPrompt(parent.id), '', 'no accidental parent scope broadening');
  const hard = projectStore.create({ title: 'Explicit delete', kind: 'project' });
  const hardNote = memory.add({ scope: 'project', project_id: hard.id, text: 'delete explicitly' });
  assert.equal((await call(`/projects/${hard.id}?mode=delete`, 'DELETE')).status, 200);
  assert.equal(memory.get(hardNote.id), null);
  // A failed chat move leaves the location in place, so its knowledge must stay active.
  const stay = projectStore.create({ title: 'Move fails', kind: 'project' });
  sessionStore.ensure('stay-chat', { project_id: stay.id });
  const stayNote = memory.add({ scope: 'project', project_id: stay.id, text: 'still active after failed delete' });
  sessionStore.moveAllInProject = () => { throw new Error('simulated move failure'); };
  const stayRes = await call(`/projects/${stay.id}`, 'DELETE');
  delete sessionStore.moveAllInProject;
  assert.notEqual(stayRes.status, 200);
  assert.ok(projectStore.get(stay.id));
  assert.equal(sessionStore.load('stay-chat').project_id, stay.id);
  assert.equal(memory.get(stayNote.id).archived_at, null, 'archive is undone when the location survives');
  assert.match(memory.formatForPrompt(stay.id), /still active after failed delete/);
  // Permanent delete: a memory cleanup failure after the project is gone is flagged, not a 500.
  const flagged = projectStore.create({ title: 'Cleanup fails', kind: 'project' });
  memory.add({ scope: 'project', project_id: flagged.id, text: 'left behind' });
  memory.saveIndex = () => { throw new Error('simulated write failure'); };
  const flaggedRes = await call(`/projects/${flagged.id}?mode=delete`, 'DELETE');
  delete memory.saveIndex;
  assert.equal(flaggedRes.status, 200);
  assert.equal(flaggedRes.data.memory_cleanup_failed, true);
  assert.ok(!projectStore.get(flagged.id));
  const fail = projectStore.create({ title: 'Must survive', kind: 'project' });
  sessionStore.ensure('survive-chat', { project_id: fail.id });
  const saveIndex = memory.saveIndex;
  memory.add({ scope: 'project', project_id: fail.id, text: 'must persist before deletion' });
  memory.saveIndex = () => { throw new Error('simulated write failure'); };
  assert.notEqual((await call(`/projects/${fail.id}`, 'DELETE')).status, 200);
  assert.ok(projectStore.get(fail.id));
  assert.equal(sessionStore.load('survive-chat').project_id, fail.id);
  memory.saveIndex = saveIndex;
  writeFileSync(path.join(dataDir, 'memory/user-memory.json'), '{broken');
  assert.notEqual((await call(`/projects/${fail.id}`, 'DELETE')).status, 200);
  assert.ok(projectStore.get(fail.id));
  assert.equal(sessionStore.load('survive-chat').project_id, fail.id);
  // Permanent delete also fails closed on an unreadable store, before chats or the project go.
  assert.notEqual((await call(`/projects/${fail.id}?mode=delete`, 'DELETE')).status, 200);
  assert.ok(projectStore.get(fail.id));
  assert.equal(sessionStore.load('survive-chat').project_id, fail.id);
  console.log('PASS memory preservation: identity/provenance/lifecycle, prompt isolation, explicit restore, dedupe/capacity, corrupt-store fail-closed, real HTTP deletion/restore/read-only, parent isolation, permanent-delete opt-in, archive undo on failed delete, permanent-delete fail-closed + cleanup flag');
} finally {
  if (server) await new Promise((resolve) => server.close(resolve));
  rmSync(dir, { recursive: true, force: true });
}
